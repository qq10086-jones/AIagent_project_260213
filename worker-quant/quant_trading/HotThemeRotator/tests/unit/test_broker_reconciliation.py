# Staleness and mark-time comparability
# ---------------------------------------------------------------------------
def test_an_old_snapshot_is_stale_not_reconciled():
    old = sbi_2026_08_14()
    view = JournalView(
        asof=date(2026, 8, 20),
        cash=287_068.0,
        quantities={"1306.T": 100, "1568.T": 60},
        mark_time="2026-08-20T15:30+09:00",
    )
    verdict = reconcile_against_broker(view, old, max_staleness_days=1)
    assert verdict.state == STALE
    assert verdict.may_write_official_nav is False


def test_navs_struck_at_different_times_are_incomparable():
    """Comparing an intraday broker total with an EOD journal NAV proves nothing."""
    view = JournalView(
        asof=date(2026, 8, 14),
        cash=287_068.0,
        quantities={"1306.T": 100, "1568.T": 60},
        mark_time="2026-08-14T11:30+09:00",  # morning session
    )
    verdict = reconcile_against_broker(view, sbi_2026_08_14())
    assert verdict.state == INCOMPARABLE_MARK_TIME
    assert verdict.may_write_official_nav is False
    # Cash and quantities are still worth reporting; only NAV is incomparable.
    assert verdict.comparable_fields == ["cash", "quantity"]


# ---------------------------------------------------------------------------
# Provisional cash: screenshots and broken tables are not money
# ---------------------------------------------------------------------------
def _cash_event(amount, provenance, provisional=None):
    entry = {
        "_type": "cash_event",
        "entry_id": f"e{abs(hash((amount, provenance)))%10**12:012d}",
        "amount": amount,
        "reason": "other",
        "source": "manual",
        "provenance": provenance,
        "ts": "2026-08-14T00:00:00+09:00",
    }
    if provisional is not None:
        entry["provisional"] = provisional
    return entry


def test_a_cash_event_read_off_a_broken_table_is_provisional():
    """The 991 case: the figure came from a table that had lost its structure."""
    events = [_cash_event(991.0, "broken_table_text")]
    result = canonical_cash(events, opening_cash=286_803.0)
    assert result["canonical_cash"] == 286_803.0, "provisional money must not be spendable"
    assert result["provisional_total"] == 991.0
    assert [e["entry_id"] for e in result["provisional_events"]] == [
        events[0]["entry_id"]
    ]


@pytest.mark.parametrize("provenance", ["screenshot", "ocr", "broken_table_text"])
def test_every_unstructured_provenance_is_provisional(provenance):
    result = canonical_cash([_cash_event(991.0, provenance)], opening_cash=0.0)
    assert result["canonical_cash"] == 0.0
    assert result["provisional_total"] == 991.0


def test_a_structured_statement_event_is_canonical():
    result = canonical_cash(
        [_cash_event(991.0, "broker_statement_csv")], opening_cash=286_803.0
    )
    assert result["canonical_cash"] == 287_794.0
    assert result["provisional_total"] == 0.0


def test_provisional_is_promoted_only_by_an_account_balance_check():
    events = [_cash_event(991.0, "broken_table_text")]
    # Broker balance disagrees -> stays provisional.
    result = canonical_cash(events, opening_cash=286_803.0, broker_cash=287_068.0)
    assert result["canonical_cash"] == 286_803.0
    assert result["promoted"] == []
    assert result["balance_check"]["agrees"] is False

    # Broker balance agrees with the event applied -> promoted.
    result = canonical_cash(events, opening_cash=286_803.0, broker_cash=287_794.0)
    assert result["canonical_cash"] == 287_794.0
    assert result["promoted"] == [events[0]["entry_id"]]
    assert result["balance_check"]["agrees"] is True


def test_an_explicit_provisional_flag_is_honoured_whatever_the_provenance():
    result = canonical_cash(
        [_cash_event(991.0, "broker_statement_csv", provisional=True)], opening_cash=0.0
    )
    assert result["canonical_cash"] == 0.0
    assert result["provisional_total"] == 991.0


