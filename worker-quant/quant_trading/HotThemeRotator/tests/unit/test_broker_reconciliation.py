# ---------------------------------------------------------------------------
# Independently constructed broker fixtures (never journal-derived)
# ---------------------------------------------------------------------------
def sbi_2026_08_14() -> BrokerSnapshot:
    """Typed from a broker account page: cash, share counts, marks, total."""
    return BrokerSnapshot(
        asof=date(2026, 8, 14),
        cash=287_068.0,
        positions={
            "1306.T": BrokerPosition(symbol="1306.T", qty=100, mark=437.8, value=43_780.0),
            "1568.T": BrokerPosition(symbol="1568.T", qty=60, mark=1052.5, value=63_150.0),
        },
        total_assets=393_998.0,
        source="sbi_web_manual",
        mark_time="2026-08-14T15:30+09:00",
    )


def journal_matching_the_broker() -> JournalView:
    return JournalView(
        asof=date(2026, 8, 14),
        cash=287_068.0,
        quantities={"1306.T": 100, "1568.T": 60},
        mark_time="2026-08-14T15:30+09:00",
    )


def journal_with_the_phantom_refund() -> JournalView:
    """The real 2026-08-14 state: +991 booked, broker says otherwise."""
    return JournalView(
        asof=date(2026, 8, 14),
        cash=287_794.0,
        quantities={"1306.T": 100, "1568.T": 60},
        mark_time="2026-08-14T15:30+09:00",
    )


# ---------------------------------------------------------------------------
# The broker's own identity comes first
# ---------------------------------------------------------------------------
def test_broker_identity_must_hold_before_anything_is_compared():
    snapshot = sbi_2026_08_14()
    identity = check_broker_identity(snapshot)
    assert identity["holds"] is True
    assert identity["cash"] == 287_068.0
    assert identity["positions_value"] == 106_930.0
    assert identity["total_assets"] == 393_998.0
    assert identity["residual"] == 0.0


def test_a_snapshot_that_does_not_add_up_is_not_evidence():
    """A mistyped or half-loaded page must not be able to reconcile anything."""
    broken = BrokerSnapshot(
        asof=date(2026, 8, 14),
        cash=287_068.0,
        positions={"1306.T": BrokerPosition("1306.T", 100, 437.8, 43_780.0)},
        total_assets=393_998.0,  # a position is missing, so this cannot balance
        source="sbi_web_manual",
        mark_time="2026-08-14T15:30+09:00",
    )
    identity = check_broker_identity(broken)
    assert identity["holds"] is False
    assert identity["residual"] == pytest.approx(63_150.0)

    verdict = reconcile_against_broker(journal_matching_the_broker(), broken)
    assert verdict.state == MISMATCH
    assert "identity" in (verdict.reason or "")
    assert verdict.may_write_official_nav is False


def test_position_value_must_match_qty_times_mark():
    """Catches a value column read from the wrong row."""
    with pytest.raises(BrokerSnapshotError, match="qty x mark"):
        BrokerPosition(symbol="1306.T", qty=100, mark=437.8, value=99_999.0).validate()


# ---------------------------------------------------------------------------
# reconciled requires external evidence
# ---------------------------------------------------------------------------
def test_reconciled_only_when_the_broker_agrees():
    verdict = reconcile_against_broker(journal_matching_the_broker(), sbi_2026_08_14())
    assert verdict.state == RECONCILED
    assert verdict.differences == []
    assert verdict.may_write_official_nav is True
    assert verdict.may_compute_return_metrics is True


def test_without_a_broker_snapshot_nothing_is_reconciled():
    """The defect in one line: no external evidence, so no external claim."""
    verdict = reconcile_against_broker(journal_matching_the_broker(), None)
    assert verdict.state == MISSING_BROKER_SNAPSHOT
    assert verdict.may_write_official_nav is False
    assert verdict.may_compute_return_metrics is False


def test_reconciled_cannot_be_derived_from_the_journal_alone():
    """A snapshot manufactured from the journal must be refused as evidence.

    This is the property that the old `reconciled_no_contradicting_evidence`
    lacked: it was computed entirely from the journal and its own advice trace,
    so it could report reconciliation while the broker disagreed by JPY 726.
    """
    view = journal_with_the_phantom_refund()
    self_made = BrokerSnapshot(
        asof=view.asof,
        cash=view.cash,
        positions={
            "1306.T": BrokerPosition("1306.T", 100, 437.8, 43_780.0),
            "1568.T": BrokerPosition("1568.T", 60, 1052.5, 63_150.0),
        },
        total_assets=view.cash + 106_930.0,
        source="derived_from_journal",
        mark_time=view.mark_time,
    )
    verdict = reconcile_against_broker(view, self_made)
    assert verdict.state == MISMATCH
    assert "source" in (verdict.reason or "")
    assert verdict.may_write_official_nav is False


# ---------------------------------------------------------------------------
# The actual 2026-08-14 failure
# ---------------------------------------------------------------------------
def test_the_2026_08_14_state_is_a_mismatch_not_a_reconciliation():
    verdict = reconcile_against_broker(journal_with_the_phantom_refund(), sbi_2026_08_14())
    assert verdict.state == MISMATCH
    cash_diff = next(d for d in verdict.differences if d["field"] == "cash")
    assert cash_diff["journal"] == 287_794.0
    assert cash_diff["broker"] == 287_068.0
    assert cash_diff["difference"] == pytest.approx(726.0)
    assert verdict.may_write_official_nav is False
    assert verdict.may_compute_return_metrics is False


def test_a_mismatch_never_proposes_a_balancing_adjustment():
    """The one thing this system must never do is invent the missing entry."""
    verdict = reconcile_against_broker(journal_with_the_phantom_refund(), sbi_2026_08_14())
    payload = verdict.to_dict()
    text = repr(payload).lower()
    assert "adjustment" not in text
    assert "suggested_entry" not in payload
    assert payload.get("proposed_correction") is None
    assert verdict.difference_is_not_an_instruction is True


def test_quantity_mismatch_is_reported_per_symbol():
    view = JournalView(
        asof=date(2026, 8, 14),
        cash=287_068.0,
        quantities={"1306.T": 100, "1568.T": 60, "8035.T": 1},  # stale phantom
        mark_time="2026-08-14T15:30+09:00",
    )
    verdict = reconcile_against_broker(view, sbi_2026_08_14())
    assert verdict.state == MISMATCH
    qty_diff = next(d for d in verdict.differences if d["field"] == "quantity:8035.T")
    assert qty_diff["journal"] == 1
    assert qty_diff["broker"] == 0


